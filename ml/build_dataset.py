"""
FILE: build_dataset.py
WHO MADE THIS: Kuldeep (data side) + Naman (agronomic rules)
WHAT IT DOES: Creates the training dataset for our AI model.

The problem: We don't have real soil test data from 1000s of farmers.
The solution: We CREATE realistic fake data using:
  1. Real NASA climate data for Indore's 5 tehsils
  2. Real soil profiles of Indore's black soil from Govt. soil cards
  3. Real agronomic rules about which crops grow in which conditions

This is called "semi-synthetic" data - the rules are 100% real,
only the individual soil numbers are generated by computer.

Output: data/raw/indore_crop_dataset.csv (1500 rows, 6 crops x 250 each)
"""

import random
import numpy as np
import pandas as pd
import os

# Fix the random seed so results are same every time (reproducibility)
SEED = 42
random.seed(SEED)
np.random.seed(SEED)

# ============================================================
# STEP 1: DEFINE WHAT WE KNOW ABOUT INDORE'S CLIMATE
# (These numbers came from NASA POWER API - 5 years of real data)
# ============================================================

# Average climate for each tehsil in Kharif (Monsoon) and Rabi (Winter)
CLIMATE = {
    ('Indore',   'Kharif'): {'temp': 28.5, 'humidity': 78.0, 'rainfall': 920},
    ('Indore',   'Rabi'):   {'temp': 19.8, 'humidity': 52.0, 'rainfall': 38},
    ('Sanwer',   'Kharif'): {'temp': 28.1, 'humidity': 75.0, 'rainfall': 890},
    ('Sanwer',   'Rabi'):   {'temp': 19.4, 'humidity': 50.0, 'rainfall': 32},
    ('Depalpur', 'Kharif'): {'temp': 28.3, 'humidity': 74.0, 'rainfall': 880},
    ('Depalpur', 'Rabi'):   {'temp': 20.1, 'humidity': 51.0, 'rainfall': 35},
    ('Mhow',     'Kharif'): {'temp': 27.9, 'humidity': 80.0, 'rainfall': 960},
    ('Mhow',     'Rabi'):   {'temp': 18.9, 'humidity': 55.0, 'rainfall': 42},
    ('Hatod',    'Kharif'): {'temp': 28.4, 'humidity': 73.0, 'rainfall': 870},
    ('Hatod',    'Rabi'):   {'temp': 20.3, 'humidity': 49.0, 'rainfall': 30},
}

# ============================================================
# STEP 2: DEFINE INDORE SOIL PROFILE
# (From Government Soil Health Card data for Indore district)
# Indore has "Vertisol" soil - deep black cotton soil
# ============================================================
SOIL_N_MIN, SOIL_N_MAX = 20,  100   # Nitrogen range for Indore black soil
SOIL_P_MIN, SOIL_P_MAX = 10,  40    # Phosphorus range
SOIL_K_MIN, SOIL_K_MAX = 150, 450   # Potassium range (naturally high in Vertisols)
SOIL_PH_MIN, SOIL_PH_MAX = 7.2, 8.2  # pH is alkaline (black soil property)

TEHSILS = ['Indore', 'Sanwer', 'Depalpur', 'Mhow', 'Hatod']
SEASONS  = ['Kharif', 'Rabi']
CROPS    = ['Soybean', 'Maize (Corn)', 'Wheat', 'Gram (Chickpea)', 'Onion', 'Potato']
SAMPLES_PER_CROP = 250  # We want exactly 250 samples for each of 6 crops = 1500 total

# ============================================================
# STEP 3: AGRONOMIC RULES
# Which crop can grow in what condition?
# (These rules are from ICAR-IISR and RVSKVV agronomic standards)
# ============================================================
def which_crops_can_grow(season, N, P, K, ph):
    """
    Returns a list of crops that can actually grow given these conditions.
    This is based on real agricultural science, not guessing.
    """
    possible = []

    if season == 'Kharif':   # Monsoon season (June - October)
        # Soybean: Needs moderate N (it fixes its own N!), good P, pH 6.8-8.0
        if 6.8 <= ph <= 8.0 and N <= 60 and P >= 40:
            possible.append('Soybean')
        # Maize: Needs more N, can handle slightly lower pH
        if 6.5 <= ph <= 7.9 and N >= 45:
            possible.append('Maize (Corn)')

    elif season == 'Rabi':   # Winter season (November - March)
        # Wheat: Heavy feeder, needs high N and P, slightly alkaline OK
        if 7.0 <= ph <= 8.2 and N >= 55 and P >= 35:
            possible.append('Wheat')
        # Gram/Chickpea: Pulse crop, likes low N (fixes own N), needs some P
        if 7.0 <= ph <= 8.2 and N <= 50 and P >= 35:
            possible.append('Gram (Chickpea)')
        # Onion: Commercial crop, needs HIGH potassium
        if 6.8 <= ph <= 8.0 and K >= 50:
            possible.append('Onion')
        # Potato: Needs lots of P and K
        if 6.5 <= ph <= 7.8 and P >= 45 and K >= 50:
            possible.append('Potato')

    return possible

# ============================================================
# STEP 4: BUILD THE DATASET
# Keep generating random soil samples until we have 250 for each crop
# ============================================================
def build_dataset():
    records = []
    crop_count = {crop: 0 for crop in CROPS}  # Track how many of each crop we have

    max_tries = 200000  # Safety limit
    tries = 0

    print("Building dataset... (this may take a moment)")

    while any(count < SAMPLES_PER_CROP for count in crop_count.values()):
        tries += 1
        if tries > max_tries:
            print("Reached maximum tries. Dataset may be slightly unbalanced.")
            break

        # Pick a random tehsil and season
        tehsil = random.choice(TEHSILS)
        season = random.choice(SEASONS)

        # Get real climate baseline and add small random variation
        climate = CLIMATE[(tehsil, season)]
        temp     = round(climate['temp']     + np.random.normal(0, 1.2),  2)
        humidity = round(np.clip(climate['humidity'] + np.random.normal(0, 3.0), 20, 95), 2)

        if season == 'Kharif':
            rainfall = round(np.clip(climate['rainfall'] + np.random.normal(0, 45), 650, 1300), 2)
        else:
            rainfall = round(np.clip(climate['rainfall'] + np.random.normal(0, 8),  10,  80),  2)

        # Generate random soil values within Indore's black soil range
        N  = round(np.clip(np.random.uniform(SOIL_N_MIN, SOIL_N_MAX) + np.random.normal(0, 2), SOIL_N_MIN, SOIL_N_MAX), 2)
        P  = round(np.clip(np.random.uniform(SOIL_P_MIN, SOIL_P_MAX) + np.random.normal(0, 2), SOIL_P_MIN, SOIL_P_MAX), 2)
        K  = round(np.clip(np.random.uniform(SOIL_K_MIN, SOIL_K_MAX) + np.random.normal(0, 2), SOIL_K_MIN, SOIL_K_MAX), 2)
        ph = round(np.clip(np.random.uniform(SOIL_PH_MIN, SOIL_PH_MAX) + np.random.normal(0, 0.05), SOIL_PH_MIN, SOIL_PH_MAX), 2)

        # Check which crops CAN grow in this condition
        possible = which_crops_can_grow(season, N, P, K, ph)
        if not possible:
            continue  # No crop can grow here, try again

        # From the possible crops, pick one that still needs more samples
        needed = [c for c in possible if crop_count[c] < SAMPLES_PER_CROP]
        if not needed:
            continue  # All matching crops are already full

        # Randomly pick one of the needed crops and add a record
        chosen_crop = random.choice(needed)
        crop_count[chosen_crop] += 1

        records.append({
            'district':    'Indore',
            'tehsil':      tehsil,
            'season':      season,
            'N':           N,
            'P':           P,
            'K':           K,
            'temperature': temp,
            'humidity':    humidity,
            'ph':          ph,
            'rainfall':    rainfall,
            'crop':        chosen_crop
        })

    # Convert to DataFrame, shuffle, and save
    df = pd.DataFrame(records).sample(frac=1, random_state=SEED).reset_index(drop=True)

    os.makedirs('data/raw', exist_ok=True)
    df.to_csv('data/raw/indore_crop_dataset.csv', index=False)

    print(f"\nDataset created with {len(df)} rows!")
    print("Crop counts:", crop_count)
    print("Saved to: data/raw/indore_crop_dataset.csv")
    return df

if __name__ == '__main__':
    build_dataset()














